def star(mean):
    v = round(rnd.gauss(mean, 0.9))
    return max(1, min(5, v))


def reviews():
    out = []
    rid = 1
    for m in MOVIES:
        for k in range(60):
            s = star(m['mean'])
            asp = {}
            if s >= 4:
                for a in rnd.sample(m['pos'], min(len(m['pos']), rnd.choice([1, 2, 2]))):
                    asp[a] = 1
            elif s <= 2:
                for a in rnd.sample(m['neg'], min(len(m['neg']), rnd.choice([1, 2]))):
                    asp[a] = -1
            else:
                asp[rnd.choice(m['pos'])] = 1
                b = rnd.choice(m['neg'])
                if b not in asp:
                    asp[b] = -1
            parts = []
            for a, p in asp.items():
                parts.append(rnd.choice(PH[a][0] if p > 0 else PH[a][1]))
            op = rnd.choice(OPEN)
            cl = rnd.choice(CLOSE_P if s >= 4 else CLOSE_N if s <= 2 else CLOSE_M)
            sep = rnd.choice([' ', '. ', ', ', ' 그리고 '])
            text = ' '.join(x for x in [op, sep.join(parts), cl] if x).strip()
            d = '2026-%02d-%02d' % (rnd.randint(1, 10), rnd.randint(1, 28))
            out.append({'id': rid, 'movie': m['id'], 'stars': s, 'date': d, 'text': text, 'asp': asp})
            rid += 1
    # 비꼬는 리뷰 3개를 붉은 계단·검은 서버실·한강 추격전에 끼운다
    for (t, a, s), mv in zip(SARCASM, [3, 8, 4]):
        out.append({'id': rid, 'movie': mv, 'stars': s, 'date': '2026-09-%02d' % (10 + rid % 9), 'text': t, 'asp': a, 'sarcasm': True})
        rid += 1
    return out


