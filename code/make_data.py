def sns():
    out = []
    pid = 1
    def add(day, text, topic, dup=0, issue=False, movie=0, asp=None):
        nonlocal pid
        out.append({'id': pid, 'day': day, 'text': text, 'topic': topic, 'dup': dup, 'issue': issue, 'movie': movie, 'asp': asp or {}})
        pid += 1
    for day in range(1, 15):
        for _ in range(4):  # 영화 이야기
            m = rnd.choice(MOVIES); good = rnd.random() < .7
            a = rnd.choice(m['pos'] if good else m['neg'])
            t = '#%s %s %s' % (m['title'].replace(' ', ''), rnd.choice(['보고 왔는데', '봤다', '어제 봄', '드디어 봄']), rnd.choice(PH[a][0] if good else PH[a][1]))
            add(day, t, 'movie', movie=m['id'], asp={a: 1 if good else -1})
        add(day, rnd.choice(FOOD), 'food')
        add(day, rnd.choice(WEATHER), 'weather')
        add(day, rnd.choice(WORK), 'work')
        for _ in range(1 if day < 9 else 2):  # 말만 바꾼 광고 글 (둘째 주에는 처음 보는 말투의 광고도 섞인다)
            g, lst = rnd.choice(PROMO) if day < 8 or rnd.random() < .5 else PROMO_NEW
            add(day, rnd.choice(lst), 'promo', dup=g)
        if day >= 9:  # 9일째부터 새 이슈가 늘어난다
            for _ in range(day - 8):
                add(day, rnd.choice(ISSUE), 'issue', issue=True)
    return out


